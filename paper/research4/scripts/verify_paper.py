"""Verify the Research 4 manuscript against the frozen evidence. Check-only by default (never modifies a tracked file).

    python verify_paper.py            verify; exit 1 on any drift
    python verify_paper.py --write    regenerate SOURCE_MAP.md and (with --freeze) PUBLICATION_FREEZE.json, then verify

The verifier does not use git. Text files are hashed after LF normalisation (checkouts may use CRLF); the PDF is hashed raw.
Checks: every claim printed in the manuscript equals the value recomputed from the frozen artifacts; every percentage and large
integer printed in the prose is a registered claim; generated tables, figure data and SOURCE_MAP.md equal their generators'
output; the classification is re-derived; identities equal the frozen records; the body carries no internal identifiers or
repository paths; every citation key exists; and, when PUBLICATION_FREEZE.json exists, the PDF and sources match it."""
from __future__ import annotations
import hashlib, json, re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent; sys.path.insert(0, str(HERE))
import frozen, claims, build_assets

TEX_NAME, BIB_NAME, PDF_NAME = "research4.tex", "research4.bib", "research4.pdf"
FORBIDDEN = [r"R[234]-0\d", r"R[234]-\d\d", r"R3-0\d", r"R2-\d\d", r"Research~?\s?[1-5]\b", r"\bR[1-5]\b", r"Phase\s?[0-3]\b", r"CFDC", r"\.json", r"\.py\b",
             r"experiments/", r"papers?/", r"Argine[234]", r"C:\\", r"/Users/", r"/home/", r"TODO", r"sprint", r"milestone", r"deliverable"]
TITLE_FORBIDDEN = [r"Research", r"\bR4\b"]


def sha_text(p: Path) -> str:
    return hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def sha_raw(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def norm(s: str) -> str:
    return s.replace("\r\n", "\n")


def source_map(rows) -> str:
    out = ["# Research 4 manuscript: source map", "",
           "Generated by `scripts/verify_paper.py --write`; checked (not rewritten) by `scripts/verify_paper.py`. Every claim below is recomputed from the frozen",
           "artifacts and must occur as printed in `research4.tex` or its generated tables. Internal identifiers are used here and not in the manuscript body.", "",
           "| Claim | Shown | Meaning | Artifact | Field | Calculation | Displayed precision |", "|---|---|---|---|---|---|---|"]
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    for r in rows:
        out.append("| " + " | ".join(esc(x) for x in (r["id"], r["shown"], r["meaning"], r["artifact"], r["field"], r["calc"], r["precision"])) + " |")
    out.append(""); return "\n".join(out)


def pdf_text_ok(pdf: Path) -> bool:
    return pdf.exists() and pdf.read_bytes()[:5] == b"%PDF-"


def verify(paper: Path = HERE.parent, write: bool = False, freeze: bool = False):
    """Return (failures, n_claims). paper: a directory laid out like paper/research4 (read-only unless write)."""
    fails = []; paper = Path(paper)
    tex_p, bib_p = paper / TEX_NAME, paper / BIB_NAME
    tex = norm(tex_p.read_text(encoding="utf-8")); bib = norm(bib_p.read_text(encoding="utf-8"))
    F = frozen.load(); rows = claims.registry(F)
    tabs = {rel: norm((paper / rel).read_text(encoding="utf-8")) for rel in sorted(str(p.relative_to(paper)).replace("\\", "/") for p in (paper / "tables").glob("*.tex"))}
    corpus = tex + "\n" + "\n".join(tabs.values()) + "\n" + norm((paper / "figures" / "fig1_design.tex").read_text(encoding="utf-8"))
    # 1. every claim occurs as printed
    for r in rows:
        if not re.search(r["pattern"], corpus):
            fails.append(f"claim {r['id']} ({r['shown']}): not found as printed in the manuscript")
    # 2. no unregistered percentage or large integer in the prose
    body = tex.split("\\appendix")[0]
    allowed = set(claims.CONST_PCT) | {t for r in rows for t in r["tokens"]}
    for m in re.finditer(r"(-?\d+(?:\.\d+)?)\\%", body):
        if m.group(1) not in allowed:
            fails.append(f"unregistered percentage in the body: {m.group(0)}")
    claimed_big = {m for r in rows for m in re.findall(r"\d{1,3}(?:\\\{,\\\}\d{3})+", r["pattern"].replace("\\\\", "\\"))}
    for m in re.finditer(r"\d{1,3}(?:\{,\}\d{3})+", body):
        s = m.group(0)
        if not any(s in r["pattern"].replace("\\", "") for r in rows if "{,}" in r["pattern"].replace("\\", "")):
            fails.append(f"unregistered large integer in the body: {s}")
    # 3. generated assets equal generators' output
    gen = build_assets.render(F)
    for rel, txt in gen.items():
        f = paper / rel
        if not f.exists():
            fails.append(f"missing generated asset {rel}")
        elif norm(f.read_text(encoding="utf-8")) != txt:
            fails.append(f"generated asset {rel} differs from its generator output")
    # 4. identities: every hex string in the appendix exists in a frozen record
    recs = "".join(p.read_text(encoding="utf-8", errors="ignore") for d in (frozen.P0, frozen.P1, frozen.P2, "experiments/R3-final-closure") for p in (frozen.REPO / d).glob("*.json"))
    for h in set(re.findall(r"\\hsh\{([0-9a-f]{40,64})\}", tex)):
        if h not in recs:
            fails.append(f"identity {h[:12]}... printed but not present in the frozen records")
    # 5. body hygiene: no internal identifiers, repository paths or project-management language outside the appendix
    for pat in FORBIDDEN:
        for m in re.finditer(pat, body):
            fails.append(f"forbidden token {m.group(0)!r} in the body (line {body[:m.start()].count(chr(10)) + 1})")
    mt = re.search(r"\\title\{(.*?)\}\s*\\author", tex, re.S); title = mt.group(1) if mt else ""
    for pat in TITLE_FORBIDDEN:
        if re.search(pat, title):
            fails.append(f"title contains {pat}")
    for pat in (r"[A-Za-z]:\\\\Users", r"/Users/\w+", r"\\\\alpel"):
        if re.search(pat, tex):
            fails.append(f"personal path in the manuscript: {pat}")
    # 6. citations
    keys = set(re.findall(r"@\w+\{([^,\s]+),", bib)); cited = {k.strip() for c in re.findall(r"\\cite\w*\{([^}]*)\}", tex) for k in c.split(",")}
    for k in sorted(cited - keys):
        fails.append(f"citation key {k} missing from the bibliography")
    # 7. source map
    sm = source_map(rows); smp = paper / "SOURCE_MAP.md"
    if write:
        smp.write_text(sm, encoding="utf-8", newline="\n")
    elif not smp.exists():
        fails.append("SOURCE_MAP.md missing")
    elif norm(smp.read_text(encoding="utf-8")) != sm:
        fails.append("SOURCE_MAP.md differs from the registry (run with --write)")
    # 8. publication freeze
    fz_p = paper / "PUBLICATION_FREEZE.json"
    pdf_p = paper / PDF_NAME
    if freeze:
        if not pdf_text_ok(pdf_p):
            fails.append("research4.pdf missing or not a PDF")
        else:
            fz = {
                "artifact": "R4-PAPER-PUBLICATION-FREEZE",
                "title": " ".join(re.sub(r"\\\\|\\textbf\{|\}|~", " ", title).split()),
                "author": "sennape", "date": "November 2026",
                "manuscript": "paper/research4/research4.tex", "pdf": "paper/research4/research4.pdf",
                "pdf_sha256": sha_raw(pdf_p), "source_map_sha256": sha_text(smp), "tex_lf_sha256": sha_text(tex_p), "bib_lf_sha256": sha_text(bib_p),
                "figure_data_lf_sha256": sha_text(paper / "figures/figure_data.json"),
                "figure_pdf_sha256": {n: sha_raw(paper / "figures" / n) for n in ("fig2_capture.pdf", "fig3_pertrace.pdf")},
                "figure_tex_lf_sha256": sha_text(paper / "figures/fig1_design.tex"),
                "table_lf_sha256": {rel: sha_text(paper / rel) for rel in tabs},
                "script_lf_sha256": {n: sha_text(HERE / n) for n in ("frozen.py", "claims.py", "build_assets.py", "verify_paper.py")},
                "classification": F["fin"]["classification"], "state": F["fin"]["r4_cfdc_state"],
                "claims_verified": len(rows),
                "r4_freezes": {"R4-00": F["f0"]["freeze_sha256"], "R4-01": F["f1"]["freeze_sha256"], "R4-02": F["f2"]["freeze_sha256"]},
                "r4_contract_digests": {"R4-00": F["f0"]["contract_digest"], "R4-01": F["f1"]["contract_digest"], "R4-02": F["f2"]["contract_digest"]},
                "verifier": "paper/research4/scripts/verify_paper.py", "verifier_result": "PASS" if not fails else "FAIL",
                "build": {"engine": "latexmk -pdf", "SOURCE_DATE_EPOCH": "1795305600", "FORCE_SOURCE_DATE": "1"},
                "note": "Does not modify any frozen contract. The publication commit is the commit that adds this file; it cannot be recorded inside it.",
            }
            if write:
                fz_p.write_text(json.dumps(fz, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    if fz_p.exists() and not freeze:
        fz = json.loads(fz_p.read_text(encoding="utf-8"))
        chk = [("pdf_sha256", sha_raw(pdf_p) if pdf_p.exists() else None), ("source_map_sha256", sha_text(smp) if smp.exists() else None), ("tex_lf_sha256", sha_text(tex_p)),
               ("bib_lf_sha256", sha_text(bib_p)), ("figure_data_lf_sha256", sha_text(paper / "figures/figure_data.json")), ("classification", F["fin"]["classification"]),
               ("claims_verified", len(rows)), ("figure_tex_lf_sha256", sha_text(paper / "figures/fig1_design.tex"))]
        for k, v in chk:
            if fz.get(k) != v:
                fails.append(f"PUBLICATION_FREEZE.{k} does not match the current file/value")
        for n, h in fz.get("figure_pdf_sha256", {}).items():
            if sha_raw(paper / "figures" / n) != h:
                fails.append(f"PUBLICATION_FREEZE figure hash mismatch: {n}")
        for rel, h in fz.get("table_lf_sha256", {}).items():
            if sha_text(paper / rel) != h:
                fails.append(f"PUBLICATION_FREEZE table hash mismatch: {rel}")
        for n, h in fz.get("script_lf_sha256", {}).items():
            if sha_text(HERE / n) != h:
                fails.append(f"PUBLICATION_FREEZE script hash mismatch: {n}")
        if fz.get("r4_freezes") != {"R4-00": F["f0"]["freeze_sha256"], "R4-01": F["f1"]["freeze_sha256"], "R4-02": F["f2"]["freeze_sha256"]}:
            fails.append("PUBLICATION_FREEZE does not reference the R4 freezes")
    return fails, len(rows)


def main(argv):
    write, freeze = "--write" in argv, "--freeze" in argv
    fails, n = verify(write=write, freeze=freeze)
    for f in fails:
        print("FAIL:", f)
    if fails:
        print(f"R4 PAPER VERIFY: FAIL ({len(fails)} problems, {n} claims)"); return 1
    print(f"R4 PAPER VERIFY: PASS ({n} claims verified; sources, assets, source map, identities and freeze consistent)"); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
